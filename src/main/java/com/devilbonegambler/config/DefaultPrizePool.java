package com.devilbonegambler.config;

import com.devilbonegambler.util.ModConstants;
import java.util.LinkedHashMap;
import java.util.Map;
import net.minecraft.network.chat.Component;

/**
 * The prize pools written when the config file does not exist yet: a pure survival scenario and a creative one.
 *
 * Every preset text is resolved once, in the language the server runs with at that moment, and then stored as a plain
 * string. The file is the only place these texts live afterwards, so a later language change never rewrites the
 * wording a player already saw.
 *
 * The table itself lives in {@link DefaultPrizePoolData}, which is generated by scripts/build_preset_pool.py.
 */
public final class DefaultPrizePool
{
    private DefaultPrizePool()
    {
    }

    public static PrizePoolBook createBook()
    {
        PrizePoolBook book = PrizePoolBook.empty();
        boolean chinese = isChinese();
        Map<String, PrizePoolConfig> pools = new LinkedHashMap<String, PrizePoolConfig>();
        Map<String, Map<Integer, PrizeRegion>> regions = new LinkedHashMap<String, Map<Integer, PrizeRegion>>();

        for (String[] row : DefaultPrizePoolData.POOLS)
        {
            PrizePoolConfig pool = PrizePoolConfig.empty();
            pool.id = row[0];
            pool.name = chinese ? row[1] : row[2];
            pool.description = chinese ? row[3] : row[4];
            pools.put(pool.id, pool);
            regions.put(pool.id, new LinkedHashMap<Integer, PrizeRegion>());
            book.pools.add(pool);
        }

        for (String[] row : DefaultPrizePoolData.ENTRIES)
        {
            PrizePoolConfig pool = pools.get(row[0]);

            if (pool == null)
            {
                continue;
            }

            int tier = Integer.parseInt(row[1]);
            Map<Integer, PrizeRegion> byTier = regions.get(row[0]);
            PrizeRegion region = byTier.get(Integer.valueOf(tier));

            if (region == null)
            {
                region = new PrizeRegion(tier);
                byTier.put(Integer.valueOf(tier), region);
                pool.regions.add(region);
            }

            region.entriesOrEmpty().add(new PrizeEntry(chinese ? row[2] : row[3], true,
                    Double.parseDouble(row[6]), row[7], Boolean.parseBoolean(row[8]), row[9],
                    ModConstants.NOTIFY_MODE_TELLRAW, chinese ? row[4] : row[5]));
        }

        book.activeId = book.pools.isEmpty() ? "" : book.pools.get(0).idOrEmpty();
        return book;
    }

    /**
     * The client language reaches the integrated server through the shared language instance, so a probe key decides
     * which column of the preset table applies. A dedicated server keeps the default language and therefore writes the
     * English column.
     */
    private static boolean isChinese()
    {
        return Component.translatable("gui." + ModConstants.MOD_ID + ".language").getString().startsWith("zh");
    }
}
