package com.devilbonegambler.config;

import com.devilbonegambler.DevilBoneGambler;
import com.devilbonegambler.util.ModConstants;
import com.google.gson.Gson;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.List;
import net.minecraft.network.chat.Component;

/**
 * The prize pools written when the config file does not exist yet: a pure survival scenario and a creative one.
 *
 * Every preset text is resolved once, in the language the server runs with at that moment, and then stored as a plain
 * string. The file is the only place these texts live afterwards, so a later language change never rewrites the
 * wording a player already saw.
 *
 * The table itself is the bundled resource {@code assets/devil_bone_gambler/prize_pools/presets.json}, generated by
 * scripts/build_preset_pool.py. It is a resource instead of a generated class so a preset set of thousands of entries
 * never becomes one huge Java method.
 */
public final class DefaultPrizePool
{
    private static final String RESOURCE = "/assets/" + ModConstants.MOD_ID + "/prize_pools/presets.json";
    private static final Gson GSON = new Gson();

    private DefaultPrizePool()
    {
    }

    public static PrizePoolBook createBook()
    {
        PresetFile file = load();
        PrizePoolBook book = PrizePoolBook.empty();

        if (file == null || file.pools == null)
        {
            DevilBoneGambler.LOGGER.warn("The preset pool resource is missing or unreadable: {}", RESOURCE);
            return book;
        }

        boolean chinese = isChinese();

        for (PresetPool preset : file.pools)
        {
            PrizePoolConfig pool = PrizePoolConfig.empty();
            pool.id = preset.id == null ? "" : preset.id;
            pool.name = chinese ? preset.nameZh : preset.nameEn;
            pool.description = chinese ? preset.descZh : preset.descEn;
            book.pools.add(pool);

            if (preset.regions == null)
            {
                continue;
            }

            for (PresetRegion presetRegion : preset.regions)
            {
                PrizeRegion region = new PrizeRegion(presetRegion.tier);
                pool.regions.add(region);

                if (presetRegion.entries == null)
                {
                    continue;
                }

                List<PrizeEntry> entries = region.entriesOrEmpty();

                for (PresetEntry presetEntry : presetRegion.entries)
                {
                    entries.add(new PrizeEntry(chinese ? presetEntry.nameZh : presetEntry.nameEn, true,
                            presetEntry.weight, presetEntry.color, presetEntry.major, presetEntry.command,
                            ModConstants.NOTIFY_MODE_TELLRAW, chinese ? presetEntry.notifyZh : presetEntry.notifyEn));
                }
            }
        }

        book.activeId = book.pools.isEmpty() ? "" : book.pools.get(0).idOrEmpty();
        return book;
    }

    private static PresetFile load()
    {
        try (InputStream stream = DefaultPrizePool.class.getResourceAsStream(RESOURCE))
        {
            if (stream == null)
            {
                return null;
            }

            return GSON.fromJson(new InputStreamReader(stream, StandardCharsets.UTF_8), PresetFile.class);
        }
        catch (Exception exception)
        {
            DevilBoneGambler.LOGGER.warn("Failed to read the preset pool resource {}", RESOURCE, exception);
            return null;
        }
    }

    /**
     * The client language reaches the integrated server through the shared language instance, so a probe key decides
     * which column of the preset table applies. A dedicated server keeps the default language and therefore writes the
     * English column.
     */
    private static boolean isChinese()
    {
        return Component.translatable("gui." + ModConstants.MOD_ID + ".language").getString().startsWith("zh");
    }

    /* The resource shape: both languages of every text travel together, and one column is picked when a world starts. */
    private static final class PresetFile
    {
        private List<PresetPool> pools;
    }

    private static final class PresetPool
    {
        private String id;
        private String nameZh;
        private String nameEn;
        private String descZh;
        private String descEn;
        private List<PresetRegion> regions;
    }

    private static final class PresetRegion
    {
        private int tier;
        private List<PresetEntry> entries;
    }

    private static final class PresetEntry
    {
        private String nameZh;
        private String nameEn;
        private String notifyZh;
        private String notifyEn;
        private double weight;
        private String color;
        private boolean major;
        private String command;
    }
}
