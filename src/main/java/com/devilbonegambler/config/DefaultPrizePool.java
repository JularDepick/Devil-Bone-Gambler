package com.devilbonegambler.config;

import com.devilbonegambler.util.ModConstants;
import java.util.Map;
import java.util.TreeMap;
import net.minecraft.network.chat.Component;

/**
 * The prize pool written when the config file does not exist yet: six regions keyed by dice point, each one holding
 * at least a hundred entries.
 *
 * Every preset name and display text is resolved once, in the language the server runs with at that moment, and then
 * stored as a plain string. The file is the only place these texts live afterwards, so a later language change never
 * rewrites the wording a player already saw.
 *
 * The table itself lives in {@link DefaultPrizePoolData}, which is generated by scripts/build_preset_pool.py.
 */
public final class DefaultPrizePool
{
    private DefaultPrizePool()
    {
    }

    public static PrizePoolConfig create()
    {
        PrizePoolConfig config = PrizePoolConfig.empty();
        Map<Integer, PrizeRegion> regions = new TreeMap<Integer, PrizeRegion>();
        boolean chinese = isChinese();

        for (String[] row : DefaultPrizePoolData.ENTRIES)
        {
            int tier = Integer.parseInt(row[0]);
            PrizeRegion region = regions.get(Integer.valueOf(tier));

            if (region == null)
            {
                region = new PrizeRegion(tier);
                regions.put(Integer.valueOf(tier), region);
            }

            region.entriesOrEmpty().add(new PrizeEntry(chinese ? row[1] : row[2], true,
                    Double.parseDouble(row[5]), row[6], Boolean.parseBoolean(row[7]), row[8],
                    ModConstants.NOTIFY_MODE_TELLRAW, chinese ? row[3] : row[4]));
        }

        config.regions.addAll(regions.values());
        return config;
    }

    /**
     * The client language reaches the integrated server through the shared language instance, so a probe key decides
     * which column of the preset table applies. A dedicated server keeps the default language and therefore writes the
     * English column.
     */
    private static boolean isChinese()
    {
        return Component.translatable("gui." + ModConstants.MOD_ID + ".language").getString().startsWith("zh");
    }
}
